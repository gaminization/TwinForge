"""
URDF Builder
Generates a complete, valid URDF file with:
  - STL mesh for every link (from point cloud → Poisson surface reconstruction)
  - Inertial parameters (mass + inertia tensor from mesh volume + density)
  - Proper joint axes and limits
  - Gazebo material tags
"""

from __future__ import annotations
import logging
from pathlib import Path
from xml.etree import ElementTree as ET
from xml.dom import minidom
import numpy as np

log = logging.getLogger(__name__)

# Density (kg/m³) per link type
DENSITY = {
    "base": 2700., "arm_link": 1500.,
    "wheel": 1100., "end_effector": 800., "other": 1200.,
}

COLORS = {
    "base":         "0.35 0.35 0.35 1.0",
    "arm_link":     "0.20 0.55 0.80 1.0",
    "end_effector": "0.90 0.50 0.10 1.0",
    "wheel":        "0.10 0.10 0.10 1.0",
    "other":        "0.65 0.65 0.65 1.0",
}

GAZEBO_MAT = {
    "base": "Gazebo/Grey", "arm_link": "Gazebo/Blue",
    "end_effector": "Gazebo/Orange", "wheel": "Gazebo/Black",
}


def build(components: list, joints: list,
          robot_name: str, output_dir: Path) -> Path:
    """
    Build URDF + STL meshes.
    Returns path to .urdf file.
    """
    output_dir = Path(output_dir)
    mesh_dir   = output_dir / "meshes"
    mesh_dir.mkdir(parents=True, exist_ok=True)

    robot_el = ET.Element("robot", name=robot_name)
    robot_el.append(ET.Comment(" Generated by TwinForge 3D "))

    # Export mesh + write <link> for every component
    for comp in components:
        mesh_path = _export_stl(comp, mesh_dir)
        _write_link(robot_el, comp, mesh_path, robot_name)

    # Write <joint>
    for joint in joints:
        _write_joint(robot_el, joint)

    # Gazebo extensions
    for comp in components:
        gz = ET.SubElement(robot_el, "gazebo", reference=comp.id)
        ET.SubElement(gz, "material").text = GAZEBO_MAT.get(comp.type, "Gazebo/White")
        ET.SubElement(gz, "selfCollide").text = "false"

    urdf_path = output_dir / f"{robot_name}.urdf"
    _pretty_write(robot_el, urdf_path)
    log.info(f"URDF → {urdf_path}")
    return urdf_path


# ── STL export ────────────────────────────────────────────────────────────────

def _export_stl(comp, mesh_dir: Path) -> Path | None:
    """Poisson reconstruction from point cloud → STL."""
    import open3d as o3d

    pcd = comp.pcd
    if pcd is None or len(np.asarray(pcd.points)) < 20:
        return None

    pcd = pcd.voxel_down_sample(0.003)
    pcd.estimate_normals(
        search_param=o3d.geometry.KDTreeSearchParamHybrid(radius=0.02, max_nn=30))
    pcd.orient_normals_consistent_tangent_plane(30)

    try:
        mesh, densities = o3d.geometry.TriangleMesh\
            .create_from_point_cloud_poisson(pcd, depth=8, scale=1.1)
        # Trim low-density vertices (reconstruction artefacts)
        keep = np.asarray(densities) > np.quantile(densities, 0.05)
        mesh.remove_vertices_by_mask(~keep)
    except Exception:
        # BPA fallback
        dists  = pcd.compute_nearest_neighbor_distance()
        radius = 3 * np.mean(dists)
        mesh   = o3d.geometry.TriangleMesh\
            .create_from_point_cloud_ball_pivoting(
                pcd, o3d.utility.DoubleVector([radius, radius*2]))

    if len(mesh.vertices) == 0:
        return None

    mesh = mesh.simplify_quadric_decimation(8000)
    mesh.remove_degenerate_triangles()
    mesh.remove_duplicated_vertices()
    mesh.compute_vertex_normals()

    # Store mesh on component for visualizer
    comp.mesh = mesh

    out = mesh_dir / f"{comp.id}.stl"
    o3d.io.write_triangle_mesh(str(out), mesh)
    return out


# ── <link> element ────────────────────────────────────────────────────────────

def _write_link(parent_el, comp, mesh_path, robot_name: str):
    link_el = ET.SubElement(parent_el, "link", name=comp.id)

    # ── inertial ────────────────────────────────────────────────────────
    mass, com, I = _inertial(comp)
    inert_el = ET.SubElement(link_el, "inertial")
    ET.SubElement(inert_el, "origin", xyz=_v3(com), rpy="0 0 0")
    ET.SubElement(inert_el, "mass",   value=_s(mass))
    ET.SubElement(inert_el, "inertia",
                  ixx=_s(I[0,0]), ixy=_s(I[0,1]), ixz=_s(I[0,2]),
                  iyy=_s(I[1,1]), iyz=_s(I[1,2]), izz=_s(I[2,2]))

    # ── visual + collision ───────────────────────────────────────────────
    if mesh_path:
        fname = f"package://{robot_name}/meshes/{mesh_path.name}"
        for tag in ("visual", "collision"):
            el  = ET.SubElement(link_el, tag)
            ET.SubElement(el, "origin", xyz="0 0 0", rpy="0 0 0")
            geo = ET.SubElement(el, "geometry")
            ET.SubElement(geo, "mesh", filename=fname)
        # Colour (visual only)
        mat = ET.SubElement(link_el.find("visual"), "material",
                            name=f"{comp.id}_mat")
        ET.SubElement(mat, "color",
                      rgba=COLORS.get(comp.type, COLORS["other"]))
    else:
        # Box fallback
        ex, ey, ez = [max(float(v), 0.01) for v in comp.extent]
        for tag in ("visual", "collision"):
            el  = ET.SubElement(link_el, tag)
            ET.SubElement(el, "origin", xyz="0 0 0", rpy="0 0 0")
            geo = ET.SubElement(el, "geometry")
            ET.SubElement(geo, "box",
                          size=f"{ex:.4f} {ey:.4f} {ez:.4f}")


# ── <joint> element ───────────────────────────────────────────────────────────

def _write_joint(parent_el, joint):
    j_el = ET.SubElement(parent_el, "joint",
                         name=joint.id, type=joint.type)
    ET.SubElement(j_el, "parent", link=joint.parent_link)
    ET.SubElement(j_el, "child",  link=joint.child_link)
    ET.SubElement(j_el, "origin",
                  xyz=_v3(joint.origin_xyz), rpy=_v3(joint.origin_rpy))

    ax = joint.axis / (np.linalg.norm(joint.axis) + 1e-9)
    ET.SubElement(j_el, "axis", xyz=_v3(ax))

    if joint.type not in ("fixed", "floating"):
        ET.SubElement(j_el, "limit",
                      lower=_s(joint.limit_lower),
                      upper=_s(joint.limit_upper),
                      effort=_s(joint.limit_effort),
                      velocity=_s(joint.limit_velocity))
        ET.SubElement(j_el, "dynamics",
                      damping="0.05", friction="0.01")


# ── Inertial computation ──────────────────────────────────────────────────────

def _inertial(comp):
    """Mass + centre of mass + 3×3 inertia tensor."""
    density = DENSITY.get(comp.type, 1200.)

    if comp.mesh is not None:
        verts = np.asarray(comp.mesh.vertices)
        tris  = np.asarray(comp.mesh.triangles)
        if len(verts) > 0 and len(tris) > 0:
            return _mesh_inertia(verts, tris, density)

    # Bounding-box approximation
    ex, ey, ez = [max(float(v), 0.005) for v in comp.extent]
    vol  = ex * ey * ez
    mass = max(density * vol, 0.001)
    com  = comp.centroid.tolist()
    Ixx  = mass/12 * (ey**2 + ez**2)
    Iyy  = mass/12 * (ex**2 + ez**2)
    Izz  = mass/12 * (ex**2 + ey**2)
    I    = np.diag([Ixx, Iyy, Izz])
    return mass, com, I


def _mesh_inertia(verts, tris, density):
    """Analytical inertia via signed-volume divergence theorem."""
    v0 = verts[tris[:,0]]; v1 = verts[tris[:,1]]; v2 = verts[tris[:,2]]
    vol  = float(np.sum(np.einsum("ij,ij->i", v0, np.cross(v1, v2)))) / 6.
    mass = max(abs(density * vol), 0.001)
    com  = verts.mean(axis=0)
    c    = verts - com
    lx, ly, lz = np.ptp(c, axis=0)
    Ixx  = mass/12*(ly**2+lz**2)
    Iyy  = mass/12*(lx**2+lz**2)
    Izz  = mass/12*(lx**2+ly**2)
    I    = np.diag([Ixx, Iyy, Izz])
    return mass, com.tolist(), I


# ── Helpers ───────────────────────────────────────────────────────────────────

def _v3(v) -> str:
    return " ".join(f"{float(x):.6f}" for x in v)

def _s(v) -> str:
    return f"{float(v):.8g}"

def _pretty_write(root, path: Path):
    raw = ET.tostring(root, encoding="unicode")
    dom = minidom.parseString(raw)
    path.write_text(dom.toprettyxml(indent="  "))
